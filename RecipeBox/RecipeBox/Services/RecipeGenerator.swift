import Foundation

/// Generates new recipes with Claude. Results are always labelled AI-generated.
enum RecipeGenerator {
    static var schema: [String: Any] {
        let recipe: [String: Any] = [
            "type": "object", "additionalProperties": false,
            "required": ["title", "description", "category", "cuisine", "difficulty", "servings", "prepMinutes",
                         "cookMinutes", "temperature", "ingredients", "steps", "tips", "tags"],
            "properties": [
                "title": ["type": "string"],
                "description": ["type": "string"],
                "category": ["type": "string", "enum": Recipe.defaultCategories],
                "cuisine": ["type": "string"],
                "difficulty": ["type": "string", "enum": Recipe.difficulties],
                "servings": ["type": "integer"],
                "prepMinutes": ["type": "integer"],
                "cookMinutes": ["type": "integer"],
                "temperature": ["type": "string", "description": "Oven/cooking temperature in °C and °F, or empty"],
                "ingredients": ["type": "array", "items": ["type": "string"], "description": "Each with amount and unit first, e.g. '200 g chicken thighs'"],
                "steps": ["type": "array", "items": ["type": "string"]],
                "tips": ["type": "array", "items": ["type": "string"]],
                "tags": ["type": "array", "items": ["type": "string", "enum": Recipe.suggestedTags]]
            ]
        ]
        return [
            "type": "object", "additionalProperties": false, "required": ["recipes"],
            "properties": ["recipes": ["type": "array", "items": recipe]]
        ]
    }

    static let system = """
    You are a skilled recipe developer. Create practical, home-cook-friendly recipes that actually work.
    - Give every ingredient a specific amount and unit (amount first).
    - Steps must be complete and in order, with times, heat levels and doneness cues.
    - Include safe internal temperatures for meat, poultry, fish and eggs where relevant \
    (USDA: poultry 165°F/74°C; ground meat 160°F/71°C; whole cuts of beef, pork, lamb and fish 145°F/63°C).
    - Respect every constraint in the request (time, diet, budget, equipment, servings).
    - Don't claim nutrition numbers; the app calculates its own estimate.
    """

    static func generate(prompt: String, servings: Int, count: Int = 1) async throws -> [RecipeDraft] {
        let request = """
        \(prompt)

        Servings: \(servings) unless the request says otherwise.
        Create \(count) distinct recipe\(count == 1 ? "" : "s").
        """
        let obj = try await ClaudeClient.structured(system: system, content: [ClaudeClient.text(request)],
                                                    schema: schema, effort: "medium")
        let list = obj["recipes"] as? [[String: Any]] ?? []
        return list.map(draft)
    }

    static func draft(_ o: [String: Any]) -> RecipeDraft {
        var d = RecipeDraft()
        d.title = o["title"] as? String ?? "AI Recipe"
        d.summary = o["description"] as? String ?? ""
        d.category = o["category"] as? String ?? "Dinner"
        d.cuisine = o["cuisine"] as? String ?? ""
        d.tags = o["tags"] as? [String] ?? []
        d.servings = o["servings"] as? Int ?? 4
        d.servingsStatus = .confirmed
        d.prepMinutes = o["prepMinutes"] as? Int ?? 0
        d.prepStatus = d.prepMinutes > 0 ? .confirmed : .unavailable
        d.cookMinutes = o["cookMinutes"] as? Int ?? 0
        d.cookStatus = d.cookMinutes > 0 ? .confirmed : .unavailable
        d.temperature = o["temperature"] as? String ?? ""
        d.temperatureStatus = d.temperature.isEmpty ? .unavailable : .confirmed
        d.ingredients = (o["ingredients"] as? [String] ?? []).map { DraftLine(text: $0, status: .confirmed) }
        d.steps = (o["steps"] as? [String] ?? []).map { DraftLine(text: $0, status: .confirmed) }
        d.tips = o["tips"] as? [String] ?? []
        d.sourceKind = "ai"
        d.platform = ""
        d.originNote = "AI-generated recipe — not tested by a person. Check amounts, times and food safety before cooking."
        d.evidence = ["Generated by \(ClaudeClient.model.label)"]
        if let diff = o["difficulty"] as? String { d.tags = d.tags.filter { $0 != diff } }
        d.recomputeCompleteness()
        d.completeness = d.hasContent ? .complete : .none
        d.warnings = []
        d.difficulty = o["difficulty"] as? String ?? ""
        return d
    }
}
